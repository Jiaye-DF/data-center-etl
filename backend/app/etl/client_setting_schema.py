def _create_table_sql(table: str, uid_column: str, business_columns: str) -> str:
    """組出單表 `CREATE TABLE IF NOT EXISTS`(BaseModel 共通欄位由本函式統一補齊)。"""
    return f"""
    CREATE TABLE IF NOT EXISTS {CLIENT_SETTING_SCHEMA}.{table} (
        pid bigint GENERATED BY DEFAULT AS IDENTITY
            CONSTRAINT pk_{table} PRIMARY KEY,
        {uid_column} uuid NOT NULL DEFAULT gen_random_uuid()
            CONSTRAINT uq_{table}_{uid_column} UNIQUE,
{business_columns}
        is_deleted boolean NOT NULL DEFAULT false,
        created_at timestamp NOT NULL DEFAULT {_NOW_TW},
        updated_at timestamp NOT NULL DEFAULT {_NOW_TW},
        created_by uuid NOT NULL DEFAULT '{ZERO_UUID}',
        updated_by uuid NOT NULL DEFAULT '{ZERO_UUID}'
    )
    """


