def _comment_statements() -> list[str]:
    """組出全部 `COMMENT ON`(冪等:重下即覆寫同值)。"""
    statements: list[str] = []
    for table, uid_column, _ in _TABLE_DDL:
        qualified = f"{CLIENT_SETTING_SCHEMA}.{table}"
        statements.append(f"COMMENT ON TABLE {qualified} IS '{_TABLE_COMMENTS[table]}'")
        statements.append(f"COMMENT ON COLUMN {qualified}.{uid_column} IS '{_UID_COMMENT}'")
        for column, comment in _BUSINESS_COLUMN_COMMENTS[table].items():
            statements.append(f"COMMENT ON COLUMN {qualified}.{column} IS '{comment}'")
        for column, comment in _BASE_COLUMN_COMMENTS.items():
            statements.append(f"COMMENT ON COLUMN {qualified}.{column} IS '{comment}'")
    return statements


async def ensure_client_setting_schema(conn: AsyncConnection) -> None:
    """冪等建置 `client_setting` schema 與 12 張權限表(存在則略過,不刪除既有結構)。"""
    await conn.execute(text(f"CREATE SCHEMA IF NOT EXISTS {CLIENT_SETTING_SCHEMA}"))
    for table, uid_column, business_columns in _TABLE_DDL:
        await conn.execute(text(_create_table_sql(table, uid_column, business_columns)))
    for index_name, table, column in _FK_INDEX_DDL:
        await conn.execute(
            text(
                f"CREATE INDEX IF NOT EXISTS {index_name}"
                f" ON {CLIENT_SETTING_SCHEMA}.{table} ({column})"
            )
        )
    for index_name, table, columns in _UNIQUE_INDEX_DDL:
        await conn.execute(
            text(
                f"CREATE UNIQUE INDEX IF NOT EXISTS {index_name}"
                f" ON {CLIENT_SETTING_SCHEMA}.{table} ({columns})"
                " WHERE is_deleted = false"
            )
        )
    for statement in _comment_statements():
        await conn.execute(text(statement))


@asynccontextmanager
async def client_setting_engine() -> AsyncIterator[AsyncEngine]:
    """指向目標 RDS(權限設定真身)的 engine;離開 context 即釋放連線。"""
    engine = create_async_engine(rds_database_url(RDS_TARGET_DB_ENV), poolclass=NullPool)
    try:
        yield engine
    finally:
        await engine.dispose()


async def ensure_client_setting_schema_on_target() -> None:
    """自建連線對目標 RDS 執行冪等建置(供啟動 / 維運腳本呼叫)。"""
    async with client_setting_engine() as engine, engine.begin() as conn:
        await ensure_client_setting_schema(conn)


