"""RDS ETL-Hub `client_setting` schema 權限階層 12 表冪等建置(v1.6.1 task-001)。

權限設定的唯一真身在目標 RDS(`AWS_RDS_TARGET_DB`),供多台機器直讀;本應用只是維護
入口。建置方式比照 `app.etl.semantic_schema` 前例:`CREATE SCHEMA IF NOT EXISTS` +
逐表 `CREATE TABLE IF NOT EXISTS` + `CREATE INDEX IF NOT EXISTS`,可重複執行不報錯、
不刪除任何既有結構(**無任何 DROP**)。

**注意**:此 DDL 位於目標 RDS,不走 alembic(alembic 只管本專案自有 DB);識別字全為
白名單常值(schema / table / column / constraint 名皆固定字面量),不接受任何使用者
輸入,對齊 `docs/Design-Base/04-databases/04-sql-safety.md`。`COMMENT ON` 不支援
bind 參數,註解文字同為常值。

時間欄位:一律 naive `timestamp` 存 UTC+8(`04-databases/06-timezone.md`),禁
timestamptz;RDS 系統時鐘為 UTC,故 DEFAULT 需 `now() AT TIME ZONE 'Asia/Taipei'`
轉出本地 naive 值。

跨庫關聯:`client_roles` / `client_exception_sets` 以 `api_client_uid`(UUID)冷關聯
自有 DB 的 API Client 本體,**不建跨庫 FK**。
"""

